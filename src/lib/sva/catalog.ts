export function catalogInRadius(
  radiusMiles: number,
  center = { lat: CENTER_LAT, lon: CENTER_LON },
): (CatalogCamera & { milesFromCenter: number })[] {
  return CATALOG.filter((c) => inRadius(c, center, radiusMiles)).map((c) => ({
    ...c,
    milesFromCenter: haversineMiles(c, center),
    feedType: c.feedType ?? "simulated",
    source: c.source ?? "gateway-guide",
  }));
}
